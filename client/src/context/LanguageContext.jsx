const normalizedTranslations = Object.fromEntries(
  Object.entries(translations.am).map(([source, translated]) => [source.toLowerCase(), translated]),
)

function getInitialLanguage() {
  try {
    return localStorage.getItem('language') === 'am' ? 'am' : 'en'
  } catch {
    return 'en'
  }
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(getInitialLanguage)

  useEffect(() => {
    document.documentElement.lang = language === 'am' ? 'am' : 'en'
    try {
      localStorage.setItem('language', language)
    } catch {
      // The selected language remains active for this session if storage is unavailable.
    }
  }, [language])

  const t = useCallback((text) => {
    if (language === 'en' || typeof text !== 'string') return text
    return translations.am[text] || normalizedTranslations[text.toLowerCase()] || text
  }, [language])

  const value = useMemo(() => ({ language, setLanguage, t }), [language, t])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}
